async function runSeed() {
  try {
    await connectDB();
    await Product.deleteMany({});
    const inserted = await Product.insertMany(sampleProducts);
    console.log(
      `Seed completado: ${inserted.length} productos insertados en la colección "products".`
    );
  } catch (error) {
    console.error('Error al ejecutar el seed de MongoDB:', error.message);
    process.exitCode = 1;
  } finally {
    await mongoose.disconnect();
  }
}

